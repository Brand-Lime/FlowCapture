const LanguageContext = createContext<{
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: any, fallbackOrVariables?: any) => string;
}>({
  language: "it",
  setLanguage: () => {},
  t: (key) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  // The interface is Italian only: most screens are written directly in Italian, so switching to
  // English would only translate a few labels. A choice saved by older versions is ignored.
  const [language, setLanguageState] = useState<Language>("it");

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
  };

  const t = (key: any, fallbackOrVariables?: any) => {
    const isFallback = typeof fallbackOrVariables === "string";
    const variables = isFallback ? undefined : fallbackOrVariables;
    const fallbackStr = isFallback ? fallbackOrVariables : key;
    const dict = translations[language];
    let text = (dict as any)[key] || (translations["en"] as any)[key] || fallbackStr;
    if (variables) {
      for (const [k, v] of Object.entries(variables)) {
        text = text.replace(`{{${k}}}`, String(v));
      }
    }
    return text;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
